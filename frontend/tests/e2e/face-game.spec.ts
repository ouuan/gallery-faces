import { expect } from '@playwright/test';
import { test } from '../room-fixture';

for (const index of [0, 1]) test(`solo review and public one-life score at viewport ${index}`, async ({ guests }, info) => {
  const page = guests[index]!;
  await page.goto('/face-game?people=1,2&crop=0&grid=off&n=life');
  await page.getByRole('button', { name: '开始游戏' }).click();
  const choice = page.getByRole('button', { name: '人2', exact: true });
  await expect(choice).toBeEnabled();
  const frame = page.locator('.game-frame'), target = page.getByLabel('要辨认的人脸');
  await expect(target).toBeVisible();
  const zoom = page.getByRole('button', { name: '按住放大人脸' });
  await zoom.focus(); await page.keyboard.down('Space');
  await expect(target).toBeHidden(); await page.keyboard.up('Space');
  await expect(target).toBeVisible();
  await expect(page.getByRole('region', { name: '图片来源' })).toHaveCount(0);
  await choice.click();
  await expect(page.getByRole('button', { name: '查看结果' })).toBeVisible();
  await expect(choice).toHaveClass(/wrong/);
  await expect(page.getByRole('button', { name: '更换人脸 #1' })).toBeVisible();
  const source = page.getByRole('link', { name: 'X · alice' });
  const original = page.url();
  await source.click(); await expect(page.getByRole('dialog', { name: '帖子详情' })).toBeVisible();
  await page.goBack(); await expect(page).toHaveURL(original);
  await page.getByRole('checkbox', { name: '不是人脸' }).check();
  await page.getByRole('button', { name: '提交反馈' }).click();
  await expect(page.getByText('存疑 1', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByText(/本题已记为存疑/)).toBeVisible();
  await expect(frame).toBeVisible();
  await page.getByRole('button', { name: '查看结果' }).click();
  const summary = page.getByRole('region', { name: '本局结果' });
  await expect(summary).toContainText('已答 1 题');
  await expect(summary.getByRole('region', { name: '作答分布' }).getByRole('definition')).toHaveText(['0 题', '0 题', '1 题']);
  await page.screenshot({ path: info.outputPath('result.png') });
  await page.getByText('上榜昵称').locator('input').fill('甲');
  await page.getByRole('button', { name: '上传个人成绩' }).click();
  await expect(page.getByRole('button', { name: '成绩已提交' })).toBeVisible();
  await page.getByRole('link', { name: '当前榜单', exact: true }).click();
  await expect(page.getByRole('row', { name: /甲/ })).toContainText('0 题');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
