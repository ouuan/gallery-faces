test('solo reveals the magnified viewport and averages only correct answers', async ({ guests }, info) => {
  const [page] = guests;
  await page.goto('/face-game?people=1,2');
  await page.getByText('逐格显示', { exact: true }).click();
  const inputs = page.locator('.grid-settings input');
  await expect(inputs.nth(0)).toHaveValue('5');
  await expect(inputs.nth(1)).toHaveValue('0.5');
  await inputs.nth(0).fill('3'); await inputs.nth(0).press('Tab');
  await inputs.nth(1).fill('10'); await inputs.nth(1).press('Tab');
  await page.clock.install();
  const firstQuestion = page.waitForResponse('**/gallery/face-game?**').then(response => response.json());
  await page.getByRole('button', { name: '开始游戏' }).click();
  await expect(page.getByText('已显示 0 / 9 格')).toBeVisible();
  await expect(page.locator('.grid-mask .covered')).toHaveCount(9);
  await expect(page.locator('.game-options button:enabled')).toHaveCount(0);
  const target = page.getByLabel('要辨认的人脸');
  await expect(target).toBeVisible();
  await expect(target).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)');
  const image = (await page.locator('.game-frame img').boundingBox())!;
  const box = (await target.boundingBox())!;
  expect(box.x).toBeCloseTo(image.x + image.width * 0.1, 1);
  expect(box.y).toBeCloseTo(image.y + image.height * 0.1, 1);
  expect(box.width).toBeCloseTo(image.width * 0.4, 1);
  expect(box.height).toBeCloseTo(image.height * 0.3, 1);
  const frame = (await page.locator('.game-frame').boundingBox())!;
  expect(image.width).toBeGreaterThan(frame.width);
  const fractionalFrame = await page.addStyleTag({ content: '.game-frame { position: absolute; left: 0.5px; width: 97px !important; }' });
  const bounds = (await page.locator('.game-frame').boundingBox())!;
  const edge = { x: Math.floor(bounds.x + bounds.width) - 2, y: Math.ceil(bounds.y) + 5, width: 4, height: Math.floor(bounds.height) - 10 };
  const coveredEdge = await page.screenshot({ clip: edge });
  expect((await page.screenshot({ clip: edge, style: '.game-frame img { visibility: hidden; }' })).equals(coveredEdge)).toBe(true);
  await fractionalFrame.evaluate(style => style.remove());
  await page.screenshot({ path: info.outputPath('grid-mobile.png') });
  await page.clock.fastForward(10000);
  await expect(page.getByText('已显示 1 / 9 格')).toBeVisible();
  const mask = () => page.locator('.grid-mask i').evaluateAll(cells => cells.map(cell => cell.className));
  const winningMask = await mask();
  await page.getByRole('button', { name: '人1', exact: true }).click();
  await expect(page.getByText('答对时平均 1.0 格')).toBeVisible();
  await expect(page.locator('.grid-mask')).toHaveCount(0);
  const zoom = page.getByRole('button', { name: '按住放大人脸' });
  await zoom.focus(); await page.keyboard.down('Space');
  await expect.poll(async () => (await page.locator('.game-frame img').boundingBox())!.width).toBeCloseTo(image.width, 1);
  await page.keyboard.up('Space');
  const review = page.getByRole('button', { name: '按住查看答对时的格子' });
  await review.hover(); await page.mouse.down();
  await expect(page.getByText('已显示 1 / 9 格')).toBeVisible();
  await page.clock.fastForward(20000);
  expect(await mask()).toEqual(winningMask);
  expect((await page.locator('.game-frame img').boundingBox())!.width).toBeCloseTo(image.width, 1);
  await page.mouse.up();
  await expect(page.locator('.grid-mask')).toHaveCount(0);
  let releaseQuestion!: () => void;
  const delayedQuestion = new Promise<void>(resolve => { releaseQuestion = resolve; });
  await page.route('**/gallery/face-game?**', async route => {
    await delayedQuestion;
    await route.fulfill({ json: await firstQuestion });
  });
  await page.getByRole('button', { name: '下一题' }).click();
  await expect(page.getByText('正在出题…')).toBeVisible();
  await expect(page.locator('.grid-progress')).toHaveCount(0);
  await page.clock.fastForward(20000);
  await expect(page.locator('.grid-progress')).toHaveCount(0);
  releaseQuestion();
  await expect(page.getByLabel('要辨认的人脸')).toBeVisible();
  await expect(page.getByText('已显示 0 / 9 格')).toBeVisible();
  await page.clock.fastForward(10000);
  await page.getByRole('button', { name: '都不是', exact: true }).click();
  await expect(review).toHaveCount(0);
  await page.getByRole('button', { name: '结束本局' }).click();
  await expect(page.getByRole('region', { name: '本局结果' })).toContainText('每边 3 格 · 答对时平均 1.0 格');
  await page.reload();
  await expect(page.getByRole('radio', { name: '逐格显示' })).toBeChecked();
  await expect(inputs.nth(0)).toHaveValue('3');
});

test('grid players can retry privately and see all attempted options after the race', async ({ guests }, info) => {
  const [host, guest, late] = guests;
  await host.goto('/face-game/rooms?people=1,2');
  await host.getByText('逐格显示', { exact: true }).click();
  await expect(host.getByRole('switch', { name: '一命模式' })).toHaveCount(0);
  await expect(host.getByLabel('每题答题时间')).toHaveCount(0);
  await host.getByRole('textbox', { name: '昵称' }).fill('甲');
  await host.getByRole('button', { name: '创建并进入' }).click();
  await expect(host.getByRole('heading', { name: /等待开局/ })).toBeVisible();
  const path = new URL(host.url()).pathname;
  async function join(player: typeof host, name: string) {
    await player.goto(path);
    await player.getByRole('textbox', { name: '昵称' }).fill(name);
    await player.getByRole('button', { name: '进入房间' }).click();
  }
  await join(guest, '乙');
  let releaseImage!: () => void;
  const delayedImage = new Promise<void>(resolve => { releaseImage = resolve; });
  await guest.route('**/api/v1/**', async route => {
    if (route.request().resourceType() === 'image') await delayedImage;
    await route.fallback();
  });
  const hostLoaded = host.waitForResponse(response => response.request().postDataJSON()?.action === 'image_loaded');
  await host.getByRole('button', { name: '开始对战' }).click();
  expect((await (await hostLoaded).json()).phase).toBe('loading');
  await expect(host.getByRole('heading', { name: /等待玩家加载照片/ })).toBeVisible();
  await expect(host.locator('.grid-progress')).toHaveCount(0);
  await expect(host.locator('.grid-mask .covered')).toHaveCount(25);
  await expect(host.locator('.game-options button:enabled')).toHaveCount(0);
  const guestLoaded = guest.waitForResponse(response => response.request().postDataJSON()?.action === 'image_loaded');
  releaseImage();
  expect((await (await guestLoaded).json()).phase).toBe('answer');
  await expect(guest.locator('.grid-mask')).toBeVisible();
  await expect(guest.getByLabel('要辨认的人脸')).toBeVisible();
  const wrong = host.getByRole('button', { name: '人2', exact: true });
  await wrong.click();
  await expect(host.getByRole('button', { name: /人2/ })).toBeDisabled();
  await expect(guest.getByRole('button', { name: '人2', exact: true })).toBeEnabled();
  await host.reload();
  await expect(host.getByRole('button', { name: /人2/ })).toHaveClass(/wrong/);
  await expect(guest.locator('.option-tally, .game-options .wrong')).toHaveCount(0);
  await guest.getByRole('button', { name: '人2', exact: true }).click();
  await guest.screenshot({ path: info.outputPath('grid-desktop.png') });
  await join(late, '丙');
  await late.getByRole('button', { name: '人1', exact: true }).click();
  await expect(host.getByRole('button', { name: /人1.*丙/ })).toHaveClass(/right/);
  await expect(host.getByRole('button', { name: /人2.*2 人/ })).toBeVisible();
  const review = host.getByRole('button', { name: '按住查看答对时的格子' });
  await review.focus(); await host.keyboard.down('Space');
  await expect(host.locator('.grid-mask')).toBeVisible();
  await host.keyboard.up('Space');
  await expect(host.locator('.grid-mask')).toHaveCount(0);
  await expect(host.getByRole('button', { name: '都不是', exact: true }).locator('.option-tally')).toHaveCount(0);
  await host.getByRole('button', { name: '结束对战' }).click();
  await expect(late.getByRole('group', { name: '我的战绩' })).toContainText('第 1 名');
  await expect(late.getByRole('group', { name: '我的战绩' })).toContainText('每边 5 格');
  await expect(host.getByRole('group', { name: '我的战绩' })).toContainText('并列第 2 名');
  await expect(guest.getByRole('table').getByRole('columnheader')).toHaveText(['名次', '玩家', '分数', '正确', '错误', '平均格数']);
  expect(await host.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});

test('players can pass a fully revealed grid and reveal the answer together', async ({ guests }) => {
  const [host, guest] = guests;
  await host.goto('/face-game/rooms?people=1,2');
  await host.getByText('逐格显示', { exact: true }).click();
  const size = host.locator('.grid-settings input').first();
  await size.fill('2'); await size.press('Tab');
  await host.getByRole('textbox', { name: '昵称' }).fill('甲');
  await host.getByRole('button', { name: '创建并进入' }).click();
  await expect(host.getByRole('heading', { name: /等待开局/ })).toBeVisible();
  await guest.goto(new URL(host.url()).pathname);
  await guest.getByRole('textbox', { name: '昵称' }).fill('乙');
  await guest.getByRole('button', { name: '进入房间' }).click();
  await host.getByRole('button', { name: '开始对战' }).click();
  const pass = host.getByRole('button', { name: '放弃作答' });
  await expect(host.locator('.grid-mask')).toBeVisible();
  await expect(pass).toHaveCount(0);
  await expect(host.getByText('已显示 4 / 4 格')).toBeVisible();
  await pass.click();
  await host.reload();
  await expect(host.getByText('已放弃本题，等待其他玩家')).toBeVisible();
  await expect(host.locator('.game-options button:enabled')).toHaveCount(0);
  await expect(guest.getByRole('button', { name: '人1', exact: true })).toBeEnabled();
  await guest.getByRole('button', { name: '放弃作答' }).click();
  for (const page of [host, guest]) {
    await expect(page.getByRole('button', { name: '人1', exact: true })).toHaveClass(/right/);
    await expect(page.getByRole('button', { name: '按住查看答对时的格子' })).toHaveCount(0);
  }
});
